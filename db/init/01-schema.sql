-- Esquema de la aplicacion. Lo ejecuta la cuenta ADMINISTRATIVA, por lo que
-- las tablas pertenecen a ella y NO a la cuenta de la app.
--
-- Esto es lo que impide que la app (o quien robe sus credenciales) pueda
-- hacer ALTER / DROP / TRUNCATE sobre las tablas: solo el dueno puede.
-- Spring corre con spring.jpa.hibernate.ddl-auto=validate, asi que solo
-- comprueba que las entidades coincidan con este archivo.
--
-- Si cambia una entidad JPA hay que actualizar este archivo Y 02-grants.sh.

CREATE TABLE IF NOT EXISTS users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(30)  NOT NULL UNIQUE,
    email                VARCHAR(254) NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    role                 VARCHAR(20)  NOT NULL
                         CHECK (role IN ('COMPRADOR', 'DUENO', 'ADMIN')),
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    token_version        INTEGER      NOT NULL DEFAULT 0,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS librarys (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    nombre     VARCHAR(150) NOT NULL,
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS books (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id        BIGINT       NOT NULL REFERENCES librarys (id),
    isbn              VARCHAR(20)  NOT NULL,
    titulo            VARCHAR(255) NOT NULL,
    autor             VARCHAR(150) NOT NULL,
    fecha_publicacion DATE         NOT NULL,
    cantidad_paginas  INTEGER      NOT NULL,
    descripcion       VARCHAR(1000),
    portada_url       VARCHAR(500),
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS favorites (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    book_id    BIGINT       NOT NULL REFERENCES books (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_favorites_user_book UNIQUE (user_id, book_id)
);

CREATE INDEX IF NOT EXISTS idx_books_library   ON books (library_id);
CREATE INDEX IF NOT EXISTS idx_favorites_book  ON favorites (book_id);